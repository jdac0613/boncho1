window.flattenSubcategories = function(){
  const out=[];
  HERB_DATA.forEach(g=>g.categories.forEach(c=>c.subcategories.forEach(s=>out.push({...s, group:g.group, category:c.name, categoryKo:c.ko}))));
  return out;
};

window.herbIndex = function(){
  const map={};
  flattenSubcategories().forEach(s=>s.herbs.forEach(h=>{ map[h] = s; }));
  return map;
};
